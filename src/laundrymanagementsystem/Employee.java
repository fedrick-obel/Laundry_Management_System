    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
     
if (currentEmployeeId == -1) {
    JOptionPane.showMessageDialog(
        this, "Please find or select an employee first."
    );
    return;
}

try {
    Connection con = DBConnection.getConnection();

    String sql = "UPDATE employee SET "
               + "f_name=?, l_name=?, phone_number=?, "
               + "ROLE_role_id=?, photo_path=? "
               + "WHERE employee_id=?";

    PreparedStatement pst = con.prepareStatement(sql);

    pst.setString(1, txtfirstname.getText());
    pst.setString(2, txtxlastname.getText());
    pst.setString(3, txtphonenumber.getText());
    pst.setInt(4, Integer.parseInt(
        cmbrole.getSelectedItem().toString()
    ));
    pst.setString(5, employeePhotoPath);
    pst.setInt(6, currentEmployeeId);

    int rows = pst.executeUpdate();

    if (rows > 0) {
        JOptionPane.showMessageDialog(
            this, "Employee updated successfully."
        );
    }

    pst.close();
    con.close();

} catch (SQLException | NumberFormatException e) {
    JOptionPane.showMessageDialog(
        this, "Error updating employee: " + e.getMessage()
    );
}

    }//GEN-LAST:event_btnupdateActionPerformed

