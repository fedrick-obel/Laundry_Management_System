    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed
     try {
    String input = JOptionPane.showInputDialog(
        this,
        "Enter Employee ID:"
    );

    if (input == null || input.trim().isEmpty()) {
        return;
    }

    int employeeId = Integer.parseInt(input);

    Connection con = DBConnection.getConnection();

    String sql = "SELECT * FROM employee WHERE employee_id=?";

    PreparedStatement pst = con.prepareStatement(sql);
    pst.setInt(1, employeeId);

    ResultSet rs = pst.executeQuery();

    if (rs.next()) {

        currentEmployeeId = rs.getInt("employee_id");

        txtfirstname.setText(rs.getString("f_name"));
        txtxlastname.setText(rs.getString("l_name"));
        txtphonenumber.setText(rs.getString("phone_number"));

        cmbrole.setSelectedItem(
            String.valueOf(rs.getInt("ROLE_role_id"))
        );
        displayEmployeePhoto(rs.getString("photo_path"));
         currentIndex = -1;
    } else {
        JOptionPane.showMessageDialog(
            this,
            "Employee not found."
        );
    }

    rs.close();
    pst.close();
    con.close();

} catch (SQLException | NumberFormatException e) {
    JOptionPane.showMessageDialog(
        this,
        "Error finding employee: " + e.getMessage()
    );
}   
    }//GEN-LAST:event_btnfindActionPerformed

