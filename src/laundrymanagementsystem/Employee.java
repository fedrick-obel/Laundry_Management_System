private void displayEmployeePhoto(String photoPath) {
    if (photoPath == null || photoPath.trim().isEmpty()) {
        lblphoto.setIcon(null);
        lblphoto.setText("No Photo");
        employeePhotoPath = null;
        return;
    }

    File photoFile = new File(photoPath);

    if (photoFile.exists()) {
        employeePhotoPath = photoPath;

        ImageIcon originalIcon = new ImageIcon(photoPath);

        Image image = originalIcon.getImage().getScaledInstance(
            lblphoto.getWidth(),
            lblphoto.getHeight(),
            Image.SCALE_SMOOTH
        );

        lblphoto.setIcon(new ImageIcon(image));
        lblphoto.setText("");
    } else {
        lblphoto.setIcon(null);
        lblphoto.setText("Photo Not Found");
        employeePhotoPath = photoPath;
    }
}

   
private void displayEmployee(int index) {
    try {
        Connection con = DBConnection.getConnection();

        String sql = "SELECT * FROM employee ORDER BY employee_id";

        PreparedStatement pst = con.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        int count = 0;
        boolean found = false;

        while (rs.next()) {

            if (count == index) {

                currentEmployeeId = rs.getInt("employee_id");

                txtfirstname.setText(rs.getString("f_name"));
                txtxlastname.setText(rs.getString("l_name"));
                txtphonenumber.setText(rs.getString("phone_number"));

                cmbrole.setSelectedItem(
                    String.valueOf(rs.getInt("ROLE_role_id"))
                );

                // Display the saved photo for this employee
                displayEmployeePhoto(
                    rs.getString("photo_path")
                );

                currentIndex = index;
                found = true;
                break;
            }

            count++;
        }

        if (!found) {
            JOptionPane.showMessageDialog(
                this,
                "No employee record found."
            );
        }

        rs.close();
        pst.close();
        con.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Error displaying employee: " + e.getMessage()
        );
    }
}
  

    private void loadRoles() {
    try {
        Connection con = DBConnection.getConnection();

        String sql = "SELECT role_id FROM role ORDER BY role_id";

        PreparedStatement pst = con.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        cmbrole.removeAllItems();

        while (rs.next()) {
            cmbrole.addItem(
                String.valueOf(rs.getInt("role_id"))
            );
        }

        rs.close();
        pst.close();
        con.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Error loading roles: " + e.getMessage()
        );
    }
 }
    
   
