    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
       
    // Step 1: Check amount
    java.math.BigDecimal amount;

    try {
        String amountText = txtamountpaid.getText().trim();
        amount = new java.math.BigDecimal(amountText);

        if (amount.compareTo(java.math.BigDecimal.ZERO) < 0) {
            JOptionPane.showMessageDialog(this,
                    "Amount cannot be negative.");
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Problem with amount paid: [" 
                + txtamountpaid.getText() + "]");
        return;
    }

    // Step 2: Check payment date
    if (datePayment.getDate() == null) {
        JOptionPane.showMessageDialog(this,
                "Please select the payment date.");
        return;
    }

    // Step 3: Check payment method
    Object selected = cmbpaymentmethod.getSelectedItem();

    if (selected == null) {
        JOptionPane.showMessageDialog(this,
                "Please select a payment method.");
        return;
    }

    int methodId;

    try {
        String methodText = selected.toString().trim();

        // Extract the digits at the beginning, e.g. "1.cash" -> 1
        String idText = methodText.replaceFirst("[^0-9].*$", "");

        if (idText.isEmpty()) {
            throw new NumberFormatException("No ID found");
        }

        methodId = Integer.parseInt(idText);

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Problem with payment method: [" 
                + selected.toString() + "]");
        return;
    }

    // Step 4: Save payment
    String sql = "INSERT INTO payment "
            + "(amount_paid, payment_date, "
            + "PAYMENT_METHOD_payment_method_id) "
            + "VALUES (?, ?, ?)";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setBigDecimal(1, amount);
        pst.setTimestamp(2,
                new Timestamp(datePayment.getDate().getTime()));
        pst.setInt(3, methodId);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Payment saved successfully.");

        txtamountpaid.setText("");
        datePayment.setDate(null);
        cmbpaymentmethod.setSelectedIndex(-1);

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Database error: " + e.getMessage());
    }


 
    
    }//GEN-LAST:event_btnsaveActionPerformed

