    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
      

    String input = JOptionPane.showInputDialog(
        this, "Enter Payment ID to update:"
    );

    if (input == null || input.trim().isEmpty()) {
        return;
    }

    try {
        int paymentId = Integer.parseInt(input.trim());

        if (txtamountpaid.getText().trim().isEmpty()
                || datePayment.getDate() == null
                || cmbpaymentmethod.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(
                this, "Please fill in all payment details."
            );
            return;
        }

        java.math.BigDecimal amount =
            new java.math.BigDecimal(txtamountpaid.getText().trim());

        if (amount.compareTo(java.math.BigDecimal.ZERO) < 0) {
            JOptionPane.showMessageDialog(
                this, "Amount paid cannot be negative."
            );
            return;
        }

        int methodId = Integer.parseInt(
            cmbpaymentmethod.getSelectedItem().toString()
                .split("\\.")[0].trim()
        );

        String sql = "UPDATE payment SET amount_paid = ?, "
                + "payment_date = ?, "
                + "PAYMENT_METHOD_payment_method_id = ? "
                + "WHERE payment_id = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setBigDecimal(1, amount);
            pst.setTimestamp(
                2, new Timestamp(datePayment.getDate().getTime())
            );
            pst.setInt(3, methodId);
            pst.setInt(4, paymentId);

            int rows = pst.executeUpdate();

            if (rows > 0) {
                JOptionPane.showMessageDialog(
                    this, "Payment updated successfully."
                );
            } else {
                JOptionPane.showMessageDialog(
                    this, "Payment ID not found."
                );
            }
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
            this, "Enter a valid Payment ID and amount."
        );
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this, "Error updating payment: " + e.getMessage()
        );
    }


    
    }//GEN-LAST:event_btnupdateActionPerformed

    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed
       

    String input = JOptionPane.showInputDialog(
        this, "Enter Payment ID to find:"
    );

    if (input == null || input.trim().isEmpty()) {
        return;
    }

    try {
        int paymentId = Integer.parseInt(input.trim());

        String sql = "SELECT * FROM payment WHERE payment_id = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setInt(1, paymentId);

            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    txtamountpaid.setText(
                        rs.getBigDecimal("amount_paid").toString()
                    );

                    Timestamp paymentTimestamp =
                        rs.getTimestamp("payment_date");

                    if (paymentTimestamp != null) {
                        datePayment.setDate(
                            new java.util.Date(paymentTimestamp.getTime())
                        );
                    } else {
                        datePayment.setDate(null);
                    }

                    int methodId = rs.getInt(
                        "PAYMENT_METHOD_payment_method_id"
                    );

                    for (int i = 0; i < cmbpaymentmethod.getItemCount(); i++) {
                        String item = cmbpaymentmethod.getItemAt(i);
                        int id = Integer.parseInt(
                            item.split("\\.")[0].trim()
                        );

                        if (id == methodId) {
                            cmbpaymentmethod.setSelectedIndex(i);
                            break;
                        }
                    }

                    JOptionPane.showMessageDialog(
                        this, "Payment found successfully."
                    );
                } else {
                    JOptionPane.showMessageDialog(
                        this, "Payment ID not found."
                    );
                }
            }
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
            this, "Enter a valid numeric Payment ID."
        );
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this, "Error finding payment: " + e.getMessage()
        );
    }


    }//GEN-LAST:event_btnfindActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
        
    String input = JOptionPane.showInputDialog(
        this, "Enter Payment ID to delete:"
    );

    if (input == null || input.trim().isEmpty()) {
        return;
    }

    try {
        int paymentId = Integer.parseInt(input.trim());

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this payment?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "DELETE FROM payment WHERE payment_id = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setInt(1, paymentId);

            int rows = pst.executeUpdate();

            if (rows > 0) {
                JOptionPane.showMessageDialog(
                    this, "Payment deleted successfully."
                );
                txtamountpaid.setText("");
                datePayment.setDate(null);
                cmbpaymentmethod.setSelectedIndex(-1);
            } else {
                JOptionPane.showMessageDialog(
                    this, "Payment ID not found."
                );
            }
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
            this, "Enter a valid numeric Payment ID."
        );
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this, "Error deleting payment: " + e.getMessage()
        );
    }


    

    }//GEN-LAST:event_btndeleteActionPerformed

