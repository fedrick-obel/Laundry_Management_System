    private void loadPaymentMethods() {
    String sql = "SELECT payment_method_id, method_name "
               + "FROM payment_method";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        cmbpaymentmethod.removeAllItems();
        cmbpaymentmethod.addItem("Select Payment Method");

        while (rs.next()) {
            int id = rs.getInt("payment_method_id");
            String methodName = rs.getString("method_name");

            cmbpaymentmethod.addItem(id + " - " + methodName);
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error loading payment methods: " + e.getMessage());
    }

}
