    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
                                         
    if (currentConditionId == -1) {
        JOptionPane.showMessageDialog(this, "Please find a condition first.");
        return;
    }

    try {
        Connection con = DBConnection.getConnection();

        String sql = "UPDATE item_condition SET condition_name = ?, description = ? WHERE condition_id = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtcondition_name.getText());
        pst.setString(2, txtdescription.getText());
        pst.setInt(3, currentConditionId);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Condition updated successfully!");

    } 
    catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btnupdateActionPerformed

    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
                                        
    try {
        Connection con = DBConnection.getConnection();

        String sql = "INSERT INTO item_condition(condition_name, description) VALUES (?, ?)";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtcondition_name.getText());
        pst.setString(2, txtdescription.getText());

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Condition saved successfully!");

        txtcondition_name.setText("");
        txtdescription.setText("");
        currentConditionId = -1;

    } 
    catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
 
    }//GEN-LAST:event_btnsaveActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
                                          
    if (currentConditionId == -1) {
        JOptionPane.showMessageDialog(this, "Please find a condition first.");
        return;
    }

    try {
        Connection con = DBConnection.getConnection();

        String sql = "DELETE FROM item_condition WHERE condition_id = ?";

        PreparedStatement pst = con.prepareStatement(sql);
        pst.setInt(1, currentConditionId);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Condition deleted successfully!");

        txtcondition_name.setText("");
        txtdescription.setText("");
        currentConditionId = -1;

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btndeleteActionPerformed

