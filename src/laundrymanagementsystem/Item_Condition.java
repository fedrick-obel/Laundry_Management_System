    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed
                                        
    try {
        Connection con = DBConnection.getConnection();

        String sql = "SELECT * FROM item_condition WHERE condition_name = ?";

        PreparedStatement pst = con.prepareStatement(sql);
        pst.setString(1, txtcondition_name.getText());

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            currentConditionId = rs.getInt("condition_id");

            txtcondition_name.setText(rs.getString("condition_name"));
            txtdescription.setText(rs.getString("description"));

            JOptionPane.showMessageDialog(this, "Condition found!");
        } else {
            JOptionPane.showMessageDialog(this, "Condition not found.");
            currentConditionId = -1;
        }

        }
         catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
        }

    }//GEN-LAST:event_btnfindActionPerformed

