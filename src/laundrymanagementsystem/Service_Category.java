    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
                                                  
    if (currentCategoryId == -1) {
        JOptionPane.showMessageDialog(this, "Find a category first.");
        return;
    }

    try {
        Connection con = DBConnection.getConnection();

        String sql = "UPDATE service_category SET category_name = ?, description = ? WHERE category_id = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtcategoryname.getText());
        pst.setString(2, txtdescription.getText());
        pst.setInt(3, currentCategoryId);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Category updated successfully!");

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btnupdateActionPerformed

    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
                                              
    try {
        Connection con = DBConnection.getConnection();

        String sql = "INSERT INTO service_category(category_name, description) VALUES (?, ?)";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtcategoryname.getText());
        pst.setString(2, txtdescription.getText());

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Category saved successfully!");

        txtcategoryname.setText("");
        txtdescription.setText("");
        currentCategoryId = -1;

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btnsaveActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
                                                 
    if (currentCategoryId == -1) {
        JOptionPane.showMessageDialog(this, "Find a category first.");
        return;
    }

    try {
        Connection con = DBConnection.getConnection();

        String sql = "DELETE FROM service_category WHERE category_id = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setInt(1, currentCategoryId);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Category deleted successfully!");

        txtcategoryname.setText("");
        txtdescription.setText("");
        currentCategoryId = -1;

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btndeleteActionPerformed

