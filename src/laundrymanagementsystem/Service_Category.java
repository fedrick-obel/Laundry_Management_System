    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
                                                 
    try {
        Connection con = DBConnection.getConnection();

        String sql = "SELECT * FROM service_category WHERE category_name = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtcategoryname.getText());

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            currentCategoryId = rs.getInt("category_id");

            txtcategoryname.setText(rs.getString("category_name"));
            txtdescription.setText(rs.getString("description"));

            JOptionPane.showMessageDialog(this, "Category found!");
        } else {
            JOptionPane.showMessageDialog(this, "Category not found.");
            currentCategoryId = -1;
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_jButton3ActionPerformed

