    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
   
    if (txtservicename.getText().trim().isEmpty()
            || txtprice.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter the service name and price.");
        return;
    }

    if (cmbcategory.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this,
                "Please select a service category.");
        return;
    }

    try {
        java.math.BigDecimal price =
                new java.math.BigDecimal(txtprice.getText().trim());

        if (price.compareTo(java.math.BigDecimal.ZERO) < 0) {
            JOptionPane.showMessageDialog(this,
                    "Price cannot be negative.");
            return;
        }

        int categoryId = Integer.parseInt(
                cmbcategory.getSelectedItem().toString());

        String sql = "INSERT INTO service "
                + "(service_name, price, "
                + "SERVICE_CATEGORY_category_id, service_photo) "
                + "VALUES (?, ?, ?, ?)";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, txtservicename.getText().trim());
            pst.setBigDecimal(2, price);
            pst.setInt(3, categoryId);

            if (servicePhoto != null) {
                pst.setBytes(4, servicePhoto);
            } else {
                pst.setNull(4, java.sql.Types.BLOB);
            }

            pst.executeUpdate();
        }

        JOptionPane.showMessageDialog(this,
                "Service saved successfully!");

        txtservicename.setText("");
        txtprice.setText("");
        cmbcategory.setSelectedIndex(-1);
        lblphoto.setIcon(null);
        lblphoto.setText("No photo");

        servicePhoto = null;
        currentServiceId = -1;

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Enter a valid price and ensure a valid category is selected.");
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Database error: " + e.getMessage());
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Error saving service: " + e.getMessage());
    }


    }//GEN-LAST:event_btnsaveActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
 
    if (currentServiceId == -1) {
        JOptionPane.showMessageDialog(this,
                "Please find a service first.");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this service?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String sql = "DELETE FROM service WHERE service_id = ?";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, currentServiceId);

        int rows = pst.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this,
                    "Service deleted successfully!");

            txtservicename.setText("");
            txtprice.setText("");
            cmbcategory.setSelectedIndex(-1);

            lblphoto.setIcon(null);
            lblphoto.setText("No photo");

            servicePhoto = null;
            currentServiceId = -1;
        } else {
            JOptionPane.showMessageDialog(this,
                    "Service record was not found.");
        }

    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Could not delete service. It may be linked to an order.\n"
                + e.getMessage());
    }


    }//GEN-LAST:event_btndeleteActionPerformed

