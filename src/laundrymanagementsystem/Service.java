    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed
   
    if (txtservicename.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Enter a service name to find.");
        return;
    }

    String sql = "SELECT * FROM service WHERE service_name = ? "
               + "ORDER BY service_id DESC LIMIT 1";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, txtservicename.getText().trim());

        try (ResultSet rs = pst.executeQuery()) {
            if (rs.next()) {
                currentServiceId = rs.getInt("service_id");

                txtservicename.setText(rs.getString("service_name"));
                txtprice.setText(rs.getString("price"));

                cmbcategory.setSelectedItem(
                        String.valueOf(rs.getInt(
                                "SERVICE_CATEGORY_category_id")));

                servicePhoto = rs.getBytes("service_photo");

                if (servicePhoto != null && servicePhoto.length > 0) {
                    ImageIcon icon = new ImageIcon(servicePhoto);

                    Image image = icon.getImage().getScaledInstance(
                            lblphoto.getWidth(),
                            lblphoto.getHeight(),
                            Image.SCALE_SMOOTH);

                    lblphoto.setIcon(new ImageIcon(image));
                    lblphoto.setText("");
                } else {
                    lblphoto.setIcon(null);
                    lblphoto.setText("No photo");
                }

                JOptionPane.showMessageDialog(this,
                        "Service found successfully!");

            } else {
                currentServiceId = -1;
                servicePhoto = null;
                lblphoto.setIcon(null);
                lblphoto.setText("No photo");

                JOptionPane.showMessageDialog(this,
                        "Service not found.");
            }
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Error finding service: " + e.getMessage());
    }



    }//GEN-LAST:event_btnfindActionPerformed

    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed

    if (currentServiceId == -1) {
        JOptionPane.showMessageDialog(this,
                "Please find a service first.");
        return;
    }

    if (txtservicename.getText().trim().isEmpty()
            || txtprice.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter the service name and price.");
        return;
    }

    if (cmbcategory.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this,
                "Please select a category.");
        return;
    }

    try {
        java.math.BigDecimal price =
                new java.math.BigDecimal(txtprice.getText().trim());

        if (price.compareTo(java.math.BigDecimal.ZERO) < 0) {
            JOptionPane.showMessageDialog(this,
                    "Price cannot be negative.");
            return;
        }

        int categoryId = Integer.parseInt(
                cmbcategory.getSelectedItem().toString());

        String sql = "UPDATE service SET service_name = ?, "
                + "price = ?, SERVICE_CATEGORY_category_id = ?, "
                + "service_photo = ? WHERE service_id = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, txtservicename.getText().trim());
            pst.setBigDecimal(2, price);
            pst.setInt(3, categoryId);

            if (servicePhoto != null) {
                pst.setBytes(4, servicePhoto);
            } else {
                pst.setNull(4, java.sql.Types.BLOB);
            }

            pst.setInt(5, currentServiceId);

            int rows = pst.executeUpdate();

            if (rows > 0) {
                JOptionPane.showMessageDialog(this,
                        "Service updated successfully!");
            } else {
                JOptionPane.showMessageDialog(this,
                        "Service record was not found.");
            }
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Please enter a valid price and category.");
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Database error: " + e.getMessage());
    }


    }//GEN-LAST:event_btnupdateActionPerformed

    private void btnbrowsephotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnbrowsephotoActionPerformed
       try {
    JFileChooser chooser = new JFileChooser();

    FileNameExtensionFilter filter =
            new FileNameExtensionFilter(
                    "Image Files", "jpg", "jpeg", "png", "gif");

    chooser.setFileFilter(filter);

    int result = chooser.showOpenDialog(this);

    if (result == JFileChooser.APPROVE_OPTION) {

        File file = chooser.getSelectedFile();

        servicePhoto = Files.readAllBytes(file.toPath());

        ImageIcon icon = new ImageIcon(servicePhoto);

        Image image = icon.getImage().getScaledInstance(
                lblphoto.getWidth(),
                lblphoto.getHeight(),
                Image.SCALE_SMOOTH);

        lblphoto.setIcon(new ImageIcon(image));
        lblphoto.setText("");

    }
    }
     catch (IOException e) {
    JOptionPane.showMessageDialog(this,
            "Error loading photo: " + e.getMessage());
     }
    }//GEN-LAST:event_btnbrowsephotoActionPerformed

