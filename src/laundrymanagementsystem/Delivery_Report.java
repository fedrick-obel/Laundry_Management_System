    private void btnloadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnloadActionPerformed
        try {
    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tbldelivery_report.getModel();

    // Clear previous records
    model.setRowCount(0);

    java.sql.Connection con = DBConnection.getConnection();

    if (con == null) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Database connection failed!");
        return;
    }

    String sql = "SELECT "
            + "d.delivery_id, "
            + "d.delivery_date, "
            + "d.delivery_status, "
            + "CONCAT(c.f_name, ' ', c.l_name) AS customer_name, "
            + "c.phone_number, "
            + "ca.address, "
            + "ca.city, "
            + "CONCAT(e.f_name, ' ', e.l_name) AS employee_name "
            + "FROM delivery d "
            + "JOIN customer_address ca "
            + "ON d.CUSTOMER_ADDRESS_address_id = ca.address_id "
            + "JOIN customer c "
            + "ON ca.CUSTOMER_customer_id = c.customer_id "
            + "JOIN employee e "
            + "ON d.EMPLOYEE_employee_id = e.employee_id";

    java.sql.PreparedStatement pst = con.prepareStatement(sql);
    java.sql.ResultSet rs = pst.executeQuery();

    while (rs.next()) {
        model.addRow(new Object[]{
            rs.getInt("delivery_id"),
            rs.getString("delivery_date"),
            rs.getString("delivery_status"),
            rs.getString("customer_name"),
            rs.getString("phone_number"),
            rs.getString("address"),
            rs.getString("city"),
            rs.getString("employee_name")
        });
    }

    rs.close();
    pst.close();
    con.close();

    javax.swing.JOptionPane.showMessageDialog(
            this, "Delivery report loaded successfully!");
    }
    catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Error loading delivery report: " + e.getMessage());
}
    }//GEN-LAST:event_btnloadActionPerformed

