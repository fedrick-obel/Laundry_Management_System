    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed
                                       
    String input = JOptionPane.showInputDialog(
            this,
            "Enter Address ID to find:"
    );

    if (input == null || input.trim().isEmpty()) {
        return;
    }

    try {
        int addressId = Integer.parseInt(input.trim());

        con = DBConnection.getConnection();

        String sql = "SELECT address_id, address, city, CUSTOMER_customer_id "
                   + "FROM customer_address "
                   + "WHERE address_id=?";

        pst = con.prepareStatement(sql);
        pst.setInt(1, addressId);

        rs = pst.executeQuery();

        if (rs.next()) {
            currentAddressId = rs.getInt("address_id");

            txtaddress.setText(rs.getString("address"));
            txtcity.setText(rs.getString("city"));

            cmbcustomerid.setSelectedItem(
                    String.valueOf(rs.getInt("CUSTOMER_customer_id")));

        } else {
            JOptionPane.showMessageDialog(this,
                    "Address ID " + addressId + " was not found.");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Please enter a valid numeric Address ID.");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error finding record: " + e.getMessage());
    }

    }//GEN-LAST:event_btnfindActionPerformed

