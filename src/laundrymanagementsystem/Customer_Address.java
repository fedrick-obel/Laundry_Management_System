    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
                                           
    if (currentAddressId == 0) {
        JOptionPane.showMessageDialog(this,
                "Please select an address record to update.");
        return;
    }

    String address = txtaddress.getText().trim();
    String city = txtcity.getText().trim();

    if (cmbcustomerid.getSelectedItem() == null ||
        cmbcustomerid.getSelectedItem().toString().equals("select customer id")) {

        JOptionPane.showMessageDialog(this,
                "Please select a Customer ID.");
        return;
    }

    if (address.isEmpty() || city.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter address and city.");
        return;
    }

    int customerId = Integer.parseInt(
            cmbcustomerid.getSelectedItem().toString());

    try {
        con = DBConnection.getConnection();

        String sql = "UPDATE customer_address "
                   + "SET address=?, city=?, CUSTOMER_customer_id=? "
                   + "WHERE address_id=?";

        pst = con.prepareStatement(sql);

        pst.setString(1, address);
        pst.setString(2, city);
        pst.setInt(3, customerId);
        pst.setInt(4, currentAddressId);

        int rows = pst.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this,
                    "Customer address updated successfully.");
        } else {
            JOptionPane.showMessageDialog(this,
                    "Address record not found.");
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error updating address: " + e.getMessage());
    }

    }//GEN-LAST:event_btnupdateActionPerformed

    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed

    String address = txtaddress.getText().trim();
    String city = txtcity.getText().trim();

    if (cmbcustomerid.getSelectedItem() == null ||
        cmbcustomerid.getSelectedItem().toString().equals("select customer id")) {

        JOptionPane.showMessageDialog(this,
                "Please select a Customer ID.");
        return;
    }

    if (address.isEmpty() || city.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter address and city.");
        return;
    }

    int customerId = Integer.parseInt(
            cmbcustomerid.getSelectedItem().toString());

    try {
        con = DBConnection.getConnection();

        String sql = "INSERT INTO customer_address "
                   + "(address, city, CUSTOMER_customer_id) "
                   + "VALUES (?, ?, ?)";

        pst = con.prepareStatement(sql);

        pst.setString(1, address);
        pst.setString(2, city);
        pst.setInt(3, customerId);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Customer address saved successfully.");

        txtaddress.setText("");
        txtcity.setText("");
        cmbcustomerid.setSelectedIndex(0);

        txtaddress.requestFocus();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error saving address: " + e.getMessage());
    }

    }//GEN-LAST:event_btnsaveActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
                                          
    if (currentAddressId == 0) {
        JOptionPane.showMessageDialog(this,
                "Please select an address record to delete.");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this address?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    try {
        con = DBConnection.getConnection();

        String sql = "DELETE FROM customer_address WHERE address_id=?";

        pst = con.prepareStatement(sql);
        pst.setInt(1, currentAddressId);

        int rows = pst.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this,
                    "Customer address deleted successfully.");

            txtaddress.setText("");
            txtcity.setText("");
            cmbcustomerid.setSelectedIndex(0);

            currentAddressId = 0;
            txtaddress.requestFocus();

        } else {
            JOptionPane.showMessageDialog(this,
                    "Address record not found.");
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error deleting address: " + e.getMessage());
    }

    }//GEN-LAST:event_btndeleteActionPerformed

