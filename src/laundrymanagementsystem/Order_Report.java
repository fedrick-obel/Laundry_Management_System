    private void btnloadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnloadActionPerformed
       try {
    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tbllaundry_order_report.getModel();

    // Clear old records before loading new ones
    model.setRowCount(0);

    java.sql.Connection con = DBConnection.getConnection();

    if (con == null) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Database connection failed!");
        return;
    }

    String sql = "SELECT "
            + "lo.order_id, "
            + "lo.order_date, "
            + "lo.expected_date, "
            + "CONCAT(c.f_name, ' ', c.l_name) AS customer_name, "
            + "c.phone_number, "
            + "os.status_name, "
            + "CONCAT(e.f_name, ' ', e.l_name) AS employee_name, "
            + "d.delivery_status, "
            + "p.amount_paid "
            + "FROM laundry_order lo "
            + "JOIN customer c "
            + "ON lo.CUSTOMER_customer_id = c.customer_id "
            + "JOIN order_status os "
            + "ON lo.ORDER_STATUS_status_id = os.status_id "
            + "JOIN employee e "
            + "ON lo.EMPLOYEE_employee_id = e.employee_id "
            + "JOIN delivery d "
            + "ON lo.DELIVERY_delivery_id = d.delivery_id "
            + "JOIN payment p "
            + "ON lo.PAYMENT_payment_id = p.payment_id";

    java.sql.PreparedStatement pst = con.prepareStatement(sql);
    java.sql.ResultSet rs = pst.executeQuery();

    while (rs.next()) {
        model.addRow(new Object[]{
            rs.getInt("order_id"),
            rs.getString("order_date"),
            rs.getString("expected_date"),
            rs.getString("customer_name"),
            rs.getString("phone_number"),
            rs.getString("status_name"),
            rs.getString("employee_name"),
            rs.getString("delivery_status"),
            rs.getBigDecimal("amount_paid")
        });
    }

    rs.close();
    pst.close();
    con.close();

    javax.swing.JOptionPane.showMessageDialog(
            this, "Order report loaded successfully!");
    } 
    catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Error loading order report: " + e.getMessage());
}
    }//GEN-LAST:event_btnloadActionPerformed

