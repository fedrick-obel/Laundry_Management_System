    private void btnsave1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsave1ActionPerformed
      
    // Check whether all fields are filled
    if (txtfeedback_text.getText().trim().isEmpty()
            || dateFeedback.getDate() == null
            || cmbstatus.getSelectedItem() == null
            || cmbcustomer.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(
            this, "Please fill in all feedback details."
        );
        return;
    }

    String sql = "INSERT INTO feedback "
            + "(feedback_text, feedback_date, status, CUSTOMER_customer_id) "
            + "VALUES (?, ?, ?, ?)";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, txtfeedback_text.getText().trim());

        // Save the selected date and time as a DATETIME value
        pst.setTimestamp(
            2, new Timestamp(dateFeedback.getDate().getTime())
        );

        pst.setString(
            3, cmbstatus.getSelectedItem().toString()
        );

        pst.setInt(
            4, Integer.parseInt(
                cmbcustomer.getSelectedItem().toString()
            )
        );

        pst.executeUpdate();

        JOptionPane.showMessageDialog(
            this, "Feedback saved successfully."
        );

        // Clear fields after saving
        txtfeedback_text.setText("");
        dateFeedback.setDate(null);
        cmbstatus.setSelectedIndex(-1);
        cmbcustomer.setSelectedIndex(-1);

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
            this, "Please select a valid customer ID."
        );
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this, "Error saving feedback: " + e.getMessage()
        );
    }


    }//GEN-LAST:event_btnsave1ActionPerformed

