    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed
     

    String input = JOptionPane.showInputDialog(
        this, "Enter Feedback ID to find:"
    );

    if (input == null || input.trim().isEmpty()) {
        return;
    }

    try {
        int feedbackId = Integer.parseInt(input.trim());

        String sql = "SELECT * FROM feedback WHERE feedback_id = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setInt(1, feedbackId);

            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    txtfeedback_text.setText(
                        rs.getString("feedback_text")
                    );

                    Timestamp feedbackTimestamp =
                        rs.getTimestamp("feedback_date");

                    if (feedbackTimestamp != null) {
                        dateFeedback.setDate(
                            new java.util.Date(
                                feedbackTimestamp.getTime()
                            )
                        );
                    } else {
                        dateFeedback.setDate(null);
                    }

                    cmbstatus.setSelectedItem(rs.getString("status"));

                    String customerId =
                        String.valueOf(
                            rs.getInt("CUSTOMER_customer_id")
                        );

                    cmbcustomer.setSelectedItem(customerId);

                    JOptionPane.showMessageDialog(
                        this, "Feedback record found."
                    );
                } else {
                    JOptionPane.showMessageDialog(
                        this, "Feedback ID not found."
                    );
                }
            }
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
            this, "Please enter a valid numeric Feedback ID."
        );
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this, "Error finding feedback: " + e.getMessage()
        );
    }


    }//GEN-LAST:event_btnfindActionPerformed

