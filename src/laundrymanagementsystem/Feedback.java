    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
      

    String input = JOptionPane.showInputDialog(
        this, "Enter Feedback ID to update:"
    );

    if (input == null || input.trim().isEmpty()) {
        return;
    }

    try {
        int feedbackId = Integer.parseInt(input.trim());

        if (txtfeedback_text.getText().trim().isEmpty()
                || dateFeedback.getDate() == null
                || cmbstatus.getSelectedItem() == null
                || cmbcustomer.getSelectedItem() == null) {

            JOptionPane.showMessageDialog(
                this, "Please fill in all feedback details."
            );
            return;
        }

        String sql = "UPDATE feedback SET feedback_text = ?, "
                + "feedback_date = ?, status = ?, "
                + "CUSTOMER_customer_id = ? WHERE feedback_id = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, txtfeedback_text.getText().trim());

            pst.setTimestamp(
                2, new Timestamp(dateFeedback.getDate().getTime())
            );

            pst.setString(
                3, cmbstatus.getSelectedItem().toString()
            );

            pst.setInt(
                4, Integer.parseInt(
                    cmbcustomer.getSelectedItem().toString()
                )
            );

            pst.setInt(5, feedbackId);

            int rows = pst.executeUpdate();

            if (rows > 0) {
                JOptionPane.showMessageDialog(
                    this, "Feedback updated successfully."
                );
            } else {
                JOptionPane.showMessageDialog(
                    this, "Feedback ID not found."
                );
            }
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
            this, "Enter a valid numeric ID and customer ID."
        );
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this, "Error updating feedback: " + e.getMessage()
        );
    }


    }//GEN-LAST:event_btnupdateActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
      

    String input = JOptionPane.showInputDialog(
        this, "Enter Feedback ID to delete:"
    );

    if (input == null || input.trim().isEmpty()) {
        return;
    }

    try {
        int feedbackId = Integer.parseInt(input.trim());

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this feedback?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "DELETE FROM feedback WHERE feedback_id = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setInt(1, feedbackId);

            int rows = pst.executeUpdate();

            if (rows > 0) {
                JOptionPane.showMessageDialog(
                    this, "Feedback deleted successfully."
                );
            } else {
                JOptionPane.showMessageDialog(
                    this, "Feedback ID not found."
                );
            }
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
            this, "Please enter a valid numeric Feedback ID."
        );
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this, "Error deleting feedback: " + e.getMessage()
        );
    }



    
    }//GEN-LAST:event_btndeleteActionPerformed

