    private void btnloadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnloadActionPerformed
       try {
            javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblcustomers.getModel();

            model.setRowCount(0);

            java.sql.Connection con = DBConnection.getConnection();

        if (con == null) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Database connection failed!");
        return;
        }

        String sql = "SELECT customer_id, f_name, l_name, phone_number FROM customer";

        java.sql.PreparedStatement pst = con.prepareStatement(sql);
        java.sql.ResultSet rs = pst.executeQuery();

        while (rs.next()) {
        model.addRow(new Object[]{
            rs.getInt("customer_id"),
            rs.getString("f_name"),
            rs.getString("l_name"),
            rs.getString("phone_number")});
        }

         rs.close();
         pst.close();
         con.close();

         javax.swing.JOptionPane.showMessageDialog(this,
            "Customer report loaded successfully!");
       }    
       catch (Exception e) {
         javax.swing.JOptionPane.showMessageDialog(this,
            "Error loading customer report: " + e.getMessage());
       }
    }//GEN-LAST:event_btnloadActionPerformed

    private void btnprintActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnprintActionPerformed
        try {
    boolean complete = tblcustomers.print();

    if (complete) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Customer report printed successfully!");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Printing was cancelled.");
    }
    }  
    catch (java.awt.print.PrinterException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Error printing report: " + e.getMessage());
    }
    }//GEN-LAST:event_btnprintActionPerformed

