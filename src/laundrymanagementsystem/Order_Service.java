    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
                                        
    try {
        Connection con = DBConnection.getConnection();

        String sql = "INSERT INTO order_service(quantity, SERVICE_service_id, LAUDRY_ORDER_order_id) VALUES (?, ?, ?)";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtquantity.getText());
        pst.setInt(2, Integer.parseInt(cmbservice.getSelectedItem().toString()));
        pst.setInt(3, Integer.parseInt(cmblaundryorder.getSelectedItem().toString()));

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Order service saved successfully!");

        txtquantity.setText("");
        currentOrderServiceId = -1;

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btnsaveActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
                                              
    if (currentOrderServiceId == -1) {
        JOptionPane.showMessageDialog(this, "Please find an order service first.");
        return;
    }

    try {
        Connection con = DBConnection.getConnection();

        String sql = "DELETE FROM order_service WHERE order_service_id = ?";

        PreparedStatement pst = con.prepareStatement(sql);
        pst.setInt(1, currentOrderServiceId);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Order service deleted successfully!");

        txtquantity.setText("");
        currentOrderServiceId = -1;

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btndeleteActionPerformed

