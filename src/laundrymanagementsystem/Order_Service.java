    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed
                                       
    try {
        Connection con = DBConnection.getConnection();

        String sql = "SELECT * FROM order_service WHERE SERVICE_service_id = ? AND LAUDRY_ORDER_order_id = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setInt(1, Integer.parseInt(cmbservice.getSelectedItem().toString()));
        pst.setInt(2, Integer.parseInt(cmblaundryorder.getSelectedItem().toString()));

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            currentOrderServiceId = rs.getInt("order_service_id");

            txtquantity.setText(rs.getString("quantity"));

            JOptionPane.showMessageDialog(this, "Order service found!");
        } else {
            JOptionPane.showMessageDialog(this, "Order service not found.");
            currentOrderServiceId = -1;
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btnfindActionPerformed

