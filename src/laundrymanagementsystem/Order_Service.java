    private void loadComboBoxes() {
    try {
        Connection con = DBConnection.getConnection();

        // Load Services
        String sql1 = "SELECT service_id FROM service";
        PreparedStatement pst1 = con.prepareStatement(sql1);
        ResultSet rs1 = pst1.executeQuery();

        cmbservice.removeAllItems();

        while (rs1.next()) {
            cmbservice.addItem(rs1.getString("service_id"));
        }

        // Load Laundry Orders
        String sql2 = "SELECT order_id FROM laundry_order";
        PreparedStatement pst2 = con.prepareStatement(sql2);
        ResultSet rs2 = pst2.executeQuery();

        cmblaundryorder.removeAllItems();

        while (rs2.next()) {
            cmblaundryorder.addItem(rs2.getString("order_id"));
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

