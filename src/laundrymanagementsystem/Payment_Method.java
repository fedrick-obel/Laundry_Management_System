    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed

    String methodName = txtmethodname.getText().trim();

    if (methodName.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Enter the payment method to find.");
        txtmethodname.requestFocus();
        return;
    }

    String sql = "SELECT payment_method_id, method_name "
               + "FROM payment_method "
               + "WHERE method_name = ?";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, methodName);

        try (ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                currentPaymentMethodId =
                        rs.getInt("payment_method_id");

                txtmethodname.setText(
                        rs.getString("method_name"));

                JOptionPane.showMessageDialog(this,
                        "Payment method found successfully!");
            } else {
                JOptionPane.showMessageDialog(this,
                        "Payment method not found.");

                currentPaymentMethodId = -1;
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error finding payment method: " + e.getMessage());
    }

    }//GEN-LAST:event_btnfindActionPerformed

