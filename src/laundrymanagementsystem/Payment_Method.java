    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed

    if (currentPaymentMethodId == -1) {
        JOptionPane.showMessageDialog(this,
                "Please find a payment method before updating.");
        return;
    }

    String methodName = txtmethodname.getText().trim();

    if (methodName.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter the payment method.");
        txtmethodname.requestFocus();
        return;
    }

    String sql = "UPDATE payment_method "
               + "SET method_name = ? "
               + "WHERE payment_method_id = ?";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, methodName);
        pst.setInt(2, currentPaymentMethodId);

        int rows = pst.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this,
                    "Payment method updated successfully!");
        } else {
            JOptionPane.showMessageDialog(this,
                    "No record was updated.");
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error updating payment method: " + e.getMessage());
    }

    }//GEN-LAST:event_btnupdateActionPerformed

    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed

    String methodName = txtmethodname.getText().trim();

    if (methodName.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter the payment method.");
        txtmethodname.requestFocus();
        return;
    }

    String sql = "INSERT INTO payment_method (method_name) VALUES (?)";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, methodName);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Payment method saved successfully!");

        txtmethodname.setText("");
        txtmethodname.requestFocus();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error saving payment method: " + e.getMessage());
    }

    }//GEN-LAST:event_btnsaveActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed

    if (currentPaymentMethodId == -1) {
        JOptionPane.showMessageDialog(this,
                "Please find a payment method before deleting.");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this payment method?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String sql = "DELETE FROM payment_method "
               + "WHERE payment_method_id = ?";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, currentPaymentMethodId);

        int rows = pst.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this,
                    "Payment method deleted successfully!");

            txtmethodname.setText("");
            currentPaymentMethodId = -1;
        } else {
            JOptionPane.showMessageDialog(this,
                    "No record was deleted.");
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error deleting payment method: " + e.getMessage());
    }
        
    }//GEN-LAST:event_btndeleteActionPerformed

