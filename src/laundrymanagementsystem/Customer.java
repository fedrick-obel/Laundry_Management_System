private void displayRecord(int index) {

    try {
        con = DBConnection.getConnection();

        String sql = "SELECT customer_id, f_name, l_name, "
                   + "phone_number, FEEDBACK_feedback_id "
                   + "FROM customer "
                   + "ORDER BY customer_id";

        pst = con.prepareStatement(sql,
                ResultSet.TYPE_SCROLL_INSENSITIVE,
                ResultSet.CONCUR_READ_ONLY);

        rs = pst.executeQuery();

        if (rs.absolute(index + 1)) {

            txtfirstname.setText(rs.getString("f_name"));
            txtlastname.setText(rs.getString("l_name"));
            txtphonenumber.setText(rs.getString("phone_number"));
            

            currentIndex = index;
        }

        rs.close();
        pst.close();
        con.close();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error displaying record: " + e.getMessage());
    }
}


