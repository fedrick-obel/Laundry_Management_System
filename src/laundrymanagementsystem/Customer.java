    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
     
    String firstname = txtfirstname.getText().trim();
    String lastname = txtlastname.getText().trim();
    String phonenumber = txtphonenumber.getText().trim();

    // Check that all fields have been filled.
    if (firstname.isEmpty() || lastname.isEmpty()
            || phonenumber.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please fill in all fields.");
        return;
    }

    try {
        // Prepare a customer request for the server.
        CustomerRequest request = new CustomerRequest();

        request.setAction(CustomerRequest.SAVE);
        request.setFirstName(firstname);
        request.setLastName(lastname);
        request.setPhoneNumber(phonenumber);

        // Send the request through the network client.
        CustomerRequest response =
                LaundryClient.sendRequest(request);

        // Display the result returned by the server.
        if (response.isSuccess()) {

            JOptionPane.showMessageDialog(this,
                    response.getMessage());

            // Keep the ID of the saved customer.
            if (response.getCustomer() != null) {
                currentCustomerId =
                        response.getCustomer().getCustomerId();
            }

            txtfirstname.setText("");
            txtlastname.setText("");
            txtphonenumber.setText("");

        } else {
            JOptionPane.showMessageDialog(this,
                    response.getMessage());
        }

    } catch (java.io.IOException
            | ClassNotFoundException e) {

        JOptionPane.showMessageDialog(this,
                "Network communication failed: "
                + e.getMessage());
    }

    }//GEN-LAST:event_btnsaveActionPerformed
    
    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
                                          

    if (currentCustomerId == 0) {
        JOptionPane.showMessageDialog(this,
                "Please select a customer record first.");
        return;
    }

    int answer = JOptionPane.showConfirmDialog(this,
            "Are you sure you want to delete this customer?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION);

    if (answer != JOptionPane.YES_OPTION) {
        return;
    }

    try {
        con = DBConnection.getConnection();

        String sql = "DELETE FROM customer WHERE customer_id = ?";

        pst = con.prepareStatement(sql);
        pst.setInt(1, currentCustomerId);

        int rows = pst.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this,
                    "Customer deleted successfully.");

            txtfirstname.setText("");
            txtlastname.setText("");
            txtphonenumber.setText("");

            currentCustomerId = 0;
        } else {
            JOptionPane.showMessageDialog(this,
                    "Customer was not deleted.");
        }

        pst.close();
        con.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error deleting customer: " + e.getMessage());
    }

    }//GEN-LAST:event_btndeleteActionPerformed

