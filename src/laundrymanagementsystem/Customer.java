    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed
           String firstname = txtfirstname.getText().trim();

    // Check whether the user entered a first name.
    if (firstname.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Enter the customer's first name to search.");
        return;
    }

    try {
        // Create a request to search for a customer.
        CustomerRequest request = new CustomerRequest();

        request.setAction(CustomerRequest.FIND);
        request.setFirstName(firstname);

        // Send the request to the server.
        CustomerRequest response =
                LaundryClient.sendRequest(request);

        // Check the result returned by the server.
        if (response.isSuccess()
                && response.getCustomer() != null) {

            // Remember the ID of the customer found.
            currentCustomerId =
                    response.getCustomer().getCustomerId();

            // Display the customer's details.
            txtfirstname.setText(
                    response.getCustomer().getFirstName());

            txtlastname.setText(
                    response.getCustomer().getLastName());

            txtphonenumber.setText(
                    response.getCustomer().getPhoneNumber());

            JOptionPane.showMessageDialog(this,
                    "Customer found.");

        } else {
            // Clear the selected ID if no customer was found.
            currentCustomerId = 0;

            JOptionPane.showMessageDialog(this,
                    response.getMessage());
        }

    } catch (java.io.IOException
            | ClassNotFoundException e) {

        JOptionPane.showMessageDialog(this,
                "Network communication failed: "
                + e.getMessage());
    }
    }//GEN-LAST:event_btnfindActionPerformed

    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
                                          

    if (currentCustomerId == 0) {
        JOptionPane.showMessageDialog(this,
                "Please select a customer record first.");
        return;
    }

    String firstname = txtfirstname.getText().trim();
    String lastname = txtlastname.getText().trim();
    String phonenumber = txtphonenumber.getText().trim();

    if (firstname.isEmpty() || lastname.isEmpty()
            || phonenumber.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please fill in all fields.");
        return;
    }

    try {
        con = DBConnection.getConnection();

        String sql = "UPDATE customer SET "
                   + "f_name = ?, "
                   + "l_name = ?, "
                   + "phone_number = ? "
                   + "WHERE customer_id = ?";

        pst = con.prepareStatement(sql);

        pst.setString(1, firstname);
        pst.setString(2, lastname);
        pst.setString(3, phonenumber);
        pst.setInt(4, currentCustomerId);

        int rows = pst.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this,
                    "Customer updated successfully.");
        } else {
            JOptionPane.showMessageDialog(this,
                    "Customer was not updated.");
        }

        pst.close();
        con.close();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error updating customer: " + e.getMessage());
    }

    }//GEN-LAST:event_btnupdateActionPerformed

