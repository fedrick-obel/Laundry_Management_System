   private void loadCustomerAddresses() {
    try {
        Connection con = DBConnection.getConnection();

        String sql = "SELECT address_id FROM customer_address ORDER BY address_id";

        PreparedStatement pst = con.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        cmbcustomer_address.removeAllItems();

        while (rs.next()) {
            cmbcustomer_address.addItem(
                String.valueOf(rs.getInt("address_id"))
            );
        }

        rs.close();
        pst.close();
        con.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Error loading customer addresses: " + e.getMessage()
        );
    }
}
   
private void displayDelivery(int index) {
    String sql = "SELECT * FROM delivery ORDER BY delivery_id";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        int count = 0;

        while (rs.next()) {
            if (count == index) {
                currentDeliveryId = rs.getInt("delivery_id");

                String savedDate = rs.getString("delivery_date");

                if (savedDate == null || savedDate.trim().isEmpty()) {
                    dateDelivery.setDate(null);
                } else {
                    java.util.Date parsedDate =
                            new java.text.SimpleDateFormat("yyyy-MM-dd")
                                    .parse(savedDate);
                    dateDelivery.setDate(parsedDate);
                }

                cmbdeliverystatus.setSelectedItem(
                        rs.getString("delivery_status"));

                cmbemployee.setSelectedItem(
                        String.valueOf(
                                rs.getInt("EMPLOYEE_employee_id")));

                cmbcustomer_address.setSelectedItem(
                        String.valueOf(
                                rs.getInt("CUSTOMER_ADDRESS_address_id")));

                currentIndex = index;
                return;
            }
            count++;
        }

        JOptionPane.showMessageDialog(this, "No delivery record found.");

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error displaying delivery: " + e.getMessage());
    } catch (java.text.ParseException e) {
        JOptionPane.showMessageDialog(this,
                "Could not read the saved delivery date.");
    }
}
    
