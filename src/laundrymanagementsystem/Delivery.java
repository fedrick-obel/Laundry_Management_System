    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
       
    // Check the calendar
    if (dateDelivery.getDate() == null) {
        JOptionPane.showMessageDialog(
            this, "Please select the delivery date."
        );
        return;
    }

    // Check the combo boxes
    if (cmbdeliverystatus.getSelectedItem() == null
            || cmbemployee.getSelectedItem() == null
            || cmbcustomer_address.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(
            this, "Please select delivery status, employee and address."
        );
        return;
    }

    // Convert the selected calendar date to text
    String deliveryDate = new java.text.SimpleDateFormat("yyyy-MM-dd")
            .format(dateDelivery.getDate());

    String status = cmbdeliverystatus.getSelectedItem().toString();

    int employeeId;
    int addressId;

    try {
        employeeId = Integer.parseInt(
            cmbemployee.getSelectedItem().toString()
                .split(" - ")[0].trim()
        );

        addressId = Integer.parseInt(
            cmbcustomer_address.getSelectedItem().toString()
                .split(" - ")[0].trim()
        );

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
            this, "Could not read the employee or address ID."
        );
        return;
    }

    String sql = "INSERT INTO delivery "
            + "(delivery_date, delivery_status, "
            + "EMPLOYEE_employee_id, CUSTOMER_ADDRESS_address_id) "
            + "VALUES (?, ?, ?, ?)";

    try (java.sql.Connection con = DBConnection.getConnection();
         java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, deliveryDate);
        pst.setString(2, status);
        pst.setInt(3, employeeId);
        pst.setInt(4, addressId);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(
            this, "Delivery saved successfully."
        );

        // Clear the form after saving
        dateDelivery.setDate(null);
        cmbdeliverystatus.setSelectedIndex(-1);
        cmbemployee.setSelectedIndex(-1);
        cmbcustomer_address.setSelectedIndex(-1);

    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(
            this, "Database error: " + e.getMessage()
        );
    }

  
              
   
 
    }//GEN-LAST:event_btnsaveActionPerformed
 
    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
      

    if (currentDeliveryId == -1) {
        JOptionPane.showMessageDialog(this,
                "Please find or display a delivery before deleting.");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this delivery?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION);

    if (confirm == JOptionPane.YES_OPTION) {
        String sql = "DELETE FROM delivery WHERE delivery_id = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setInt(1, currentDeliveryId);
            int rowsDeleted = pst.executeUpdate();

            if (rowsDeleted > 0) {
                JOptionPane.showMessageDialog(this,
                        "Delivery deleted successfully!");

                dateDelivery.setDate(null);
                cmbdeliverystatus.setSelectedIndex(0);
                cmbemployee.setSelectedIndex(0);
                cmbcustomer_address.setSelectedIndex(0);

                currentDeliveryId = -1;
                currentIndex = -1;
            } else {
                JOptionPane.showMessageDialog(this,
                        "Delivery record was not found.");
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Error deleting delivery: " + e.getMessage());
        }
    }


    }//GEN-LAST:event_btndeleteActionPerformed

