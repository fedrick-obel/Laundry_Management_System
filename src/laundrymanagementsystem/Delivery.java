    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
        

    if (currentDeliveryId == -1) {
        JOptionPane.showMessageDialog(this,
                "Please find or display a delivery before updating.");
        return;
    }

    java.util.Date selectedDate = dateDelivery.getDate();

    if (selectedDate == null) {
        JOptionPane.showMessageDialog(this,
                "Please select the delivery date.");
        return;
    }

    if (cmbdeliverystatus.getSelectedItem() == null
            || cmbemployee.getSelectedItem() == null
            || cmbcustomer_address.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this,
                "Please select the delivery status, employee, and customer address.");
        return;
    }

    try {
        String deliveryDate =
                new java.text.SimpleDateFormat("yyyy-MM-dd")
                        .format(selectedDate);

        String status = cmbdeliverystatus.getSelectedItem().toString();
        int employeeId = Integer.parseInt(
        cmbemployee.getSelectedItem().toString().split(" - ")[0].trim());

        int addressId = Integer.parseInt(
        cmbcustomer_address.getSelectedItem().toString().split(" - ")[0].trim());
        String sql = "UPDATE delivery SET delivery_date = ?, "
                + "delivery_status = ?, EMPLOYEE_employee_id = ?, "
                + "CUSTOMER_ADDRESS_address_id = ? WHERE delivery_id = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, deliveryDate);
            pst.setString(2, status);
            pst.setInt(3, employeeId);
            pst.setInt(4, addressId);
            pst.setInt(5, currentDeliveryId);

            int rowsUpdated = pst.executeUpdate();

            if (rowsUpdated > 0) {
                JOptionPane.showMessageDialog(this,
                        "Delivery updated successfully!");
            } else {
                JOptionPane.showMessageDialog(this,
                        "Delivery record was not found.");
            }
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Please check the selected employee and customer address.");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error updating delivery: " + e.getMessage());
    }

                                  
   

    }//GEN-LAST:event_btnupdateActionPerformed
    
