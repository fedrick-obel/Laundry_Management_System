    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed

    String statusName = txtstatusname.getText().trim();

    if (statusName.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Enter the status name to find.");
        txtstatusname.requestFocus();
        return;
    }

    String sql = "SELECT status_id, status_name, description "
               + "FROM order_status "
               + "WHERE status_name = ?";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, statusName);

        try (ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                currentStatusId = rs.getInt("status_id");

                txtstatusname.setText(rs.getString("status_name"));
                txtdescription.setText(rs.getString("description"));

                JOptionPane.showMessageDialog(this,
                        "Order status found successfully!");
            } else {
                JOptionPane.showMessageDialog(this,
                        "Order status not found.");

                currentStatusId = -1;
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error finding order status: " + e.getMessage());
    }

    }//GEN-LAST:event_btnfindActionPerformed

    private void btnfirstActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfirstActionPerformed

    String sql = "SELECT status_id, status_name, description "
               + "FROM order_status "
               + "ORDER BY status_id ASC "
               + "LIMIT 1";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        if (rs.next()) {
            currentStatusId = rs.getInt("status_id");
            txtstatusname.setText(rs.getString("status_name"));
            txtdescription.setText(rs.getString("description"));

            currentIndex = 0;
        } else {
            JOptionPane.showMessageDialog(this,
                    "No order status records found.");
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error loading first record: " + e.getMessage());
    }

    }//GEN-LAST:event_btnfirstActionPerformed

