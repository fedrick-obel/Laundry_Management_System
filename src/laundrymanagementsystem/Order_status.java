    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed

    if (currentStatusId == -1) {
        JOptionPane.showMessageDialog(this,
                "Please find or select a status record before updating.");
        return;
    }

    String statusName = txtstatusname.getText().trim();
    String description = txtdescription.getText().trim();

    if (statusName.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter the status name.");
        txtstatusname.requestFocus();
        return;
    }

    String sql = "UPDATE order_status "
               + "SET status_name = ?, description = ? "
               + "WHERE status_id = ?";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, statusName);
        pst.setString(2, description);
        pst.setInt(3, currentStatusId);

        int rows = pst.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this,
                    "Order status updated successfully!");
        } else {
            JOptionPane.showMessageDialog(this,
                    "No record was updated.");
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error updating order status: " + e.getMessage());
    }

    }//GEN-LAST:event_btnupdateActionPerformed

    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed

    String statusName = txtstatusname.getText().trim();
    String description = txtdescription.getText().trim();

    if (statusName.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter the status name.");
        txtstatusname.requestFocus();
        return;
    }

    String sql = "INSERT INTO order_status (status_name, description) "
               + "VALUES (?, ?)";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, statusName);
        pst.setString(2, description);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Order status saved successfully!");

        txtstatusname.setText("");
        txtdescription.setText("");

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error saving order status: " + e.getMessage());
    }

    }//GEN-LAST:event_btnsaveActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed

    if (currentStatusId == -1) {
        JOptionPane.showMessageDialog(this,
                "Please find a status record before deleting.");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this order status?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String sql = "DELETE FROM order_status WHERE status_id = ?";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, currentStatusId);

        int rows = pst.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this,
                    "Order status deleted successfully!");

            txtstatusname.setText("");
            txtdescription.setText("");
            currentStatusId = -1;
        } else {
            JOptionPane.showMessageDialog(this,
                    "No record was deleted.");
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error deleting order status: " + e.getMessage());
    }

    }//GEN-LAST:event_btndeleteActionPerformed

