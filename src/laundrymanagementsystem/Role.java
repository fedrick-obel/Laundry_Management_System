    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
                                                  
    if (currentRoleId == -1) {
        JOptionPane.showMessageDialog(this, "Find a role first.");
        return;
    }

    try {
        Connection con = DBConnection.getConnection();

        String sql = "UPDATE role SET role_name = ?, description = ? WHERE role_id = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtrolename.getText());
        pst.setString(2, txtdescription.getText());
        pst.setInt(3, currentRoleId);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Role updated successfully!");

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btnupdateActionPerformed

    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
                                                
    try {
        Connection con = DBConnection.getConnection();

        String sql = "INSERT INTO role(role_name, description) VALUES (?, ?)";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtrolename.getText());
        pst.setString(2, txtdescription.getText());

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Role saved successfully!");

        txtrolename.setText("");
        txtdescription.setText("");
        currentRoleId = -1;

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btnsaveActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
                                                
    if (currentRoleId == -1) {
        JOptionPane.showMessageDialog(this, "Find a role first.");
        return;
    }

    try {
        Connection con = DBConnection.getConnection();

        String sql = "DELETE FROM role WHERE role_id = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setInt(1, currentRoleId);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Role deleted successfully!");

        txtrolename.setText("");
        txtdescription.setText("");
        currentRoleId = -1;

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btndeleteActionPerformed

