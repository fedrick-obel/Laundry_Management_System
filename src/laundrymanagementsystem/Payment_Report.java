    private void btnloadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnloadActionPerformed
      try {
    javax.swing.table.DefaultTableModel model =
    (javax.swing.table.DefaultTableModel) tblpayment_report.getModel();

    // Clear existing rows
    model.setRowCount(0);

    // Connect to the existing database
    java.sql.Connection con = DBConnection.getConnection();

    if (con == null) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Database connection failed!");
        return;
    }

    // Retrieve payment details and payment method names
    String sql = "SELECT p.payment_id, p.amount_paid, "
            + "p.payment_date, pm.method_name "
            + "FROM payment p "
            + "JOIN payment_method pm "
            + "ON p.PAYMENT_METHOD_payment_method_id = pm.payment_method_id";

    java.sql.PreparedStatement pst = con.prepareStatement(sql);
    java.sql.ResultSet rs = pst.executeQuery();

    while (rs.next()) {
        model.addRow(new Object[]{
            rs.getInt("payment_id"),
            rs.getBigDecimal("amount_paid"),
            rs.getString("payment_date"),
            rs.getString("method_name")
        });
    }

    rs.close();
    pst.close();
    con.close();

    javax.swing.JOptionPane.showMessageDialog(this,
            "Payment report loaded successfully!");
    } 
    catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Error loading payment report: " + e.getMessage());
}
    }//GEN-LAST:event_btnloadActionPerformed

