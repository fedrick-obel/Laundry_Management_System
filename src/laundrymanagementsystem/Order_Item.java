    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed
                                        
    try {
        Connection con = DBConnection.getConnection();

        String sql = "SELECT * FROM order_item WHERE ITEM_TYPE_item_type_id = ? AND ITEM_CONDITION_condition_id = ? AND LAUDRY_ORDER_order_id = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setInt(1, Integer.parseInt(cmbitemtype.getSelectedItem().toString()));
        pst.setInt(2, Integer.parseInt(cmbitemcondition.getSelectedItem().toString()));
        pst.setInt(3, Integer.parseInt(cmblaundryorder.getSelectedItem().toString()));

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            currentOrderItemId = rs.getInt("order_item_id");

            txtquantity.setText(rs.getString("quantity"));

            JOptionPane.showMessageDialog(this, "Order item found!");
        } else {
            JOptionPane.showMessageDialog(this, "Order item not found.");
            currentOrderItemId = -1;
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btnfindActionPerformed

    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
                                          
    if (currentOrderItemId == -1) {
        JOptionPane.showMessageDialog(this, "Please find an order item first.");
        return;
    }

    try {
        Connection con = DBConnection.getConnection();

        String sql = "UPDATE order_item SET quantity = ?, ITEM_TYPE_item_type_id = ?, ITEM_CONDITION_condition_id = ?, LAUDRY_ORDER_order_id = ? WHERE order_item_id = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtquantity.getText());
        pst.setInt(2, Integer.parseInt(cmbitemtype.getSelectedItem().toString()));
        pst.setInt(3, Integer.parseInt(cmbitemcondition.getSelectedItem().toString()));
        pst.setInt(4, Integer.parseInt(cmblaundryorder.getSelectedItem().toString()));
        pst.setInt(5, currentOrderItemId);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Order item updated successfully!");

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btnupdateActionPerformed

    private void btnclearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnclearActionPerformed
                                                 
    txtquantity.setText("");
    currentOrderItemId = -1;

    if (cmbitemtype.getItemCount() > 0) {
        cmbitemtype.setSelectedIndex(0);
    }

    if (cmbitemcondition.getItemCount() > 0) {
        cmbitemcondition.setSelectedIndex(0);
    }

    if (cmblaundryorder.getItemCount() > 0) {
        cmblaundryorder.setSelectedIndex(0);
    }

    }//GEN-LAST:event_btnclearActionPerformed

