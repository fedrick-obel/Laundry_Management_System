    private void loadComboBoxes() {
    try {
        Connection con = DBConnection.getConnection();

        // Load Item Types
        String sql1 = "SELECT item_type_id FROM item_type";
        PreparedStatement pst1 = con.prepareStatement(sql1);
        ResultSet rs1 = pst1.executeQuery();

        cmbitemtype.removeAllItems();

        while (rs1.next()) {
            cmbitemtype.addItem(rs1.getString("item_type_id"));
        }

        // Load Item Conditions
        String sql2 = "SELECT condition_id FROM item_condition";
        PreparedStatement pst2 = con.prepareStatement(sql2);
        ResultSet rs2 = pst2.executeQuery();

        cmbitemcondition.removeAllItems();

        while (rs2.next()) {
            cmbitemcondition.addItem(rs2.getString("condition_id"));
        }

        // Load Laundry Orders
        String sql3 = "SELECT order_id FROM laundry_order";
        PreparedStatement pst3 = con.prepareStatement(sql3);
        ResultSet rs3 = pst3.executeQuery();

        cmblaundryorder.removeAllItems();

        while (rs3.next()) {
            cmblaundryorder.addItem(rs3.getString("order_id"));
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

