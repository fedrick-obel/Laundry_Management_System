    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
                                       
    try {
        Connection con = DBConnection.getConnection();

        String sql = "INSERT INTO order_item(quantity, ITEM_TYPE_item_type_id, ITEM_CONDITION_condition_id, LAUDRY_ORDER_order_id) VALUES (?, ?, ?, ?)";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtquantity.getText());
        pst.setInt(2, Integer.parseInt(cmbitemtype.getSelectedItem().toString()));
        pst.setInt(3, Integer.parseInt(cmbitemcondition.getSelectedItem().toString()));
        pst.setInt(4, Integer.parseInt(cmblaundryorder.getSelectedItem().toString()));

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Order item saved successfully!");

        txtquantity.setText("");
        currentOrderItemId = -1;

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btnsaveActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
                                                  
    if (currentOrderItemId == -1) {
        JOptionPane.showMessageDialog(this, "Please find an order item first.");
        return;
    }

    try {
        Connection con = DBConnection.getConnection();

        String sql = "DELETE FROM order_item WHERE order_item_id = ?";

        PreparedStatement pst = con.prepareStatement(sql);
        pst.setInt(1, currentOrderItemId);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Order item deleted successfully!");

        txtquantity.setText("");
        currentOrderItemId = -1;

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_btndeleteActionPerformed

