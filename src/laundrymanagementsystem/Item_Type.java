    private void btnbrowsephotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnbrowsephotoActionPerformed

    JFileChooser fileChooser = new JFileChooser();

    fileChooser.setDialogTitle("Select Item Type Photo");

    fileChooser.setFileFilter(
        new FileNameExtensionFilter(
            "Image Files", "jpg", "jpeg", "png", "gif"
        )
    );

    int result = fileChooser.showOpenDialog(this);

    if (result == JFileChooser.APPROVE_OPTION) {
        File selectedFile = fileChooser.getSelectedFile();

        itemPhotoPath = selectedFile.getAbsolutePath();

        ImageIcon originalIcon = new ImageIcon(itemPhotoPath);

        Image image = originalIcon.getImage().getScaledInstance(
            lblphoto.getWidth(),
            lblphoto.getHeight(),
            Image.SCALE_SMOOTH
        );

        lblphoto.setIcon(new ImageIcon(image));
        lblphoto.setText("");
    }

    }//GEN-LAST:event_btnbrowsephotoActionPerformed

