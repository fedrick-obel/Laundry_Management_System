    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnupdateActionPerformed
     
    try {
        if (currentItemTypeId == -1) {
            JOptionPane.showMessageDialog(this,
                    "Please find an Item Type first.");
            return;
        }

        if (itemPhotoPath == null || itemPhotoPath.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "No photo selected. Browse and select a photo first.");
            return;
        }

        Connection con = DBConnection.getConnection();

        String sql = "UPDATE item_type SET item_type_name = ?, "
                + "description = ?, item_photo = ? "
                + "WHERE item_type_id = ?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtitem_type_name.getText());
        pst.setString(2, txtdescription.getText());
        pst.setString(3, itemPhotoPath);
        pst.setInt(4, currentItemTypeId);

        int rows = pst.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this,"Item Type updated successfully!\n"+ "Record ID: " + currentItemTypeId+ "\nPhoto path: " + itemPhotoPath);
        } else {
            JOptionPane.showMessageDialog(this,
                    "No record was updated. Please find the item again.");
        }

        pst.close();
        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_btnupdateActionPerformed

    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
     
    try {
        Connection con = DBConnection.getConnection();

        String sql = "INSERT INTO item_type "
                + "(item_type_name, description, item_photo) "
                + "VALUES (?, ?, ?)";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtitem_type_name.getText());
        pst.setString(2, txtdescription.getText());
        pst.setString(3, itemPhotoPath);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Item Type saved successfully!");

        // Clear the text fields
        txtitem_type_name.setText("");
        txtdescription.setText("");

        // Clear the selected photo
        itemPhotoPath = null;
        lblphoto.setIcon(null);
        lblphoto.setText("No Photo");

        pst.close();
        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());
    }


    }//GEN-LAST:event_btnsaveActionPerformed

    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
   
    try {
        if (currentItemTypeId == -1) {
            JOptionPane.showMessageDialog(this,
                    "Please find an Item Type first.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete this Item Type?",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm == JOptionPane.YES_OPTION) {

            Connection con = DBConnection.getConnection();

            String sql = "DELETE FROM item_type WHERE item_type_id = ?";

            PreparedStatement pst = con.prepareStatement(sql);

            pst.setInt(1, currentItemTypeId);

            int rows = pst.executeUpdate();

            if (rows > 0) {
                JOptionPane.showMessageDialog(this,
                        "Item Type deleted successfully!");

                // Clear the text fields
                txtitem_type_name.setText("");
                txtdescription.setText("");

                // Clear the photo
                itemPhotoPath = null;
                lblphoto.setIcon(null);
                lblphoto.setText("No Photo");

                // Reset the selected record ID
                currentItemTypeId = -1;
            }

            pst.close();
            con.close();
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btndeleteActionPerformed

