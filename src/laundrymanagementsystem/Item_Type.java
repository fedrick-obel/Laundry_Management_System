    private void btnfindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnfindActionPerformed
      
    try {
        Connection con = DBConnection.getConnection();

       String sql = "SELECT * FROM item_type "
        + "WHERE item_type_name = ? "
        + "ORDER BY item_type_id DESC LIMIT 1";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, txtitem_type_name.getText());

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            currentItemTypeId = rs.getInt("item_type_id");

            txtitem_type_name.setText(rs.getString("item_type_name"));
            txtdescription.setText(rs.getString("description"));

            // Retrieve the saved photo path
            itemPhotoPath = rs.getString("item_photo");

            // Display the saved photo
            if (itemPhotoPath != null && !itemPhotoPath.isEmpty()) {

                ImageIcon originalIcon = new ImageIcon(itemPhotoPath);

                Image image = originalIcon.getImage().getScaledInstance(
                        lblphoto.getWidth(),
                        lblphoto.getHeight(),
                        Image.SCALE_SMOOTH
                );

                lblphoto.setIcon(new ImageIcon(image));
                lblphoto.setText("");

            } else {

                lblphoto.setIcon(null);
                lblphoto.setText("No Photo");
            }

            JOptionPane.showMessageDialog(this,
                    "Item Type found!");

        } else {

            currentItemTypeId = -1;
            itemPhotoPath = null;

            lblphoto.setIcon(null);
            lblphoto.setText("No Photo");

            JOptionPane.showMessageDialog(this,
                    "Item Type not found!");
        }

        rs.close();
        pst.close();
        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnfindActionPerformed

